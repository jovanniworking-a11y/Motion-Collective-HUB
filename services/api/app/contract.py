# Applied only to tables this process just created. Existing Neon policies stay.
_POSTGRES_LOCK = """
CREATE OR REPLACE FUNCTION motion_sim_runs_lock() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'sim_runs is insert-only';
END;
$$
"""

_POSTGRES_TRIGGER = """
DROP TRIGGER IF EXISTS sim_runs_no_mutate ON sim_runs
"""

_POSTGRES_TRIGGER_CREATE = """
CREATE TRIGGER sim_runs_no_mutate
BEFORE UPDATE OR DELETE ON sim_runs
FOR EACH ROW EXECUTE FUNCTION motion_sim_runs_lock()
"""


class ContractError(Exception):
    def __init__(self, status: int, detail: str) -> None:
        self.status = status
        self.detail = detail
        super().__init__(detail)


_sqlite_engine: Engine | None = None


def contract_engine() -> Engine:
    """Postgres uses the shared Neon engine. SQLite uses the contract file."""
    global _sqlite_engine
    if not DATABASE_URL.startswith("sqlite"):
        return get_engine()
    if _sqlite_engine is None:
        path = DATA_DIR / "motion_contract.sqlite3"
        path.parent.mkdir(parents=True, exist_ok=True)
        _sqlite_engine = create_engine(
            f"sqlite:///{path.as_posix()}",
            future=True,
            connect_args={"check_same_thread": False},
        )
    return _sqlite_engine


def bootstrap_contract_schema() -> None:
    """Create missing contract tables. Does not alter a table that already exists."""
    engine = contract_engine()
    with engine.begin() as conn:
        _create_missing(conn)


def insert_sim_run(body: dict[str, Any]) -> dict[str, Any]:
    row = _require_object(body, {"sim_id", "event_id", "model", "params_json", "predicted_peak_curve"})
    _allow(row, {"sim_id", "event_id", "model", "params_json", "predicted_peak_curve", "locked_at"})
    _reject_tree(row, BANNED_KEYS)
    values = {
        "sim_id": _ident(row["sim_id"], "sim_id"),
        "event_id": _ident(row["event_id"], "event_id"),
        "model": _text(row["model"], "model", 128),
        "params_json": _json_object(row["params_json"], "params_json"),
        "predicted_peak_curve": _json_curve(row["predicted_peak_curve"]),
        "locked_at": _timestamp(row["locked_at"], "locked_at") if "locked_at" in row else _now(),
    }
    _reject_tree(values["params_json"], BANNED_KEYS)
    _reject_tree(values["predicted_peak_curve"], BANNED_KEYS)
    return {"id": _write_insert("sim_runs", values, conflict_field="sim_id")}


def upsert_zone(body: dict[str, Any]) -> dict[str, Any]:
    row = _require_object(body, {"zone_id", "event_id", "name"})
    _allow(row, {"zone_id", "event_id", "name", "area_sqft", "capacity_rule"})
    _reject_tree(row, BANNED_KEYS)
    values = {
        "zone_id": _ident(row["zone_id"], "zone_id"),
        "event_id": _ident(row["event_id"], "event_id"),
        "name": _text(row["name"], "name", 128),
    }
    if "area_sqft" in row:
        values["area_sqft"] = _optional_number(row["area_sqft"], "area_sqft")
    if "capacity_rule" in row:
        values["capacity_rule"] = _optional_text(row["capacity_rule"], "capacity_rule", 256)
    return {"id": _write_upsert("zones", values, pk="zone_id")}


def upsert_event(body: dict[str, Any]) -> dict[str, Any]:
    row = _require_object(body, {"event_id", "name"})
    _allow(row, {"event_id", "name", "starts_at", "cap", "zone_map_version"})
    _reject_tree(row, BANNED_KEYS)
    values = {
        "event_id": _ident(row["event_id"], "event_id"),
        "name": _text(row["name"], "name", 128),
    }
    if "starts_at" in row:
        values["starts_at"] = None if row["starts_at"] is None else _timestamp(row["starts_at"], "starts_at")
    if "cap" in row:
        values["cap"] = _optional_int(row["cap"], "cap")
    if "zone_map_version" in row:
        values["zone_map_version"] = _optional_text(row["zone_map_version"], "zone_map_version", 64)
    return {"id": _write_upsert("events", values, pk="event_id")}


def insert_occupancy_sample(body: dict[str, Any]) -> dict[str, Any]:
    row = _require_object(
        body,
        {"ts", "event_id", "zone_id", "headcount", "source", "confidence"},
    )
    _allow(row, {"ts", "event_id", "zone_id", "headcount", "source", "confidence"})
    _reject_tree(row, PERSON_KEYS)
    headcount = _int(row["headcount"], "headcount")
    if headcount < 0:
        raise ContractError(400, "headcount must be zero or greater")
    confidence = _number(row["confidence"], "confidence")
    if not 0 <= confidence <= 1:
        raise ContractError(400, "confidence must be between 0 and 1")
    values = {
        "ts": _timestamp(row["ts"], "ts"),
        "event_id": _ident(row["event_id"], "event_id"),
        "zone_id": _ident(row["zone_id"], "zone_id"),
        "headcount": headcount,
        "source": _text(row["source"], "source", 64),
        "confidence": confidence,
    }
    return {"id": _write_insert("occupancy_samples", values)}


def insert_drink_event(body: dict[str, Any]) -> dict[str, Any]:
    row = _require_object(body, {"ts", "event_id", "drink_id", "qty"})
    _allow(row, {"ts", "event_id", "drink_id", "qty"})
    _reject_tree(row, PERSON_KEYS)
    qty = _number(row["qty"], "qty")
    if qty <= 0:
        raise ContractError(400, "qty must be greater than zero")
    values = {
        "ts": _timestamp(row["ts"], "ts"),
        "event_id": _ident(row["event_id"], "event_id"),
        "drink_id": _ident(row["drink_id"], "drink_id"),
        "qty": qty,
    }
    return {"id": _write_insert("drink_events", values)}


def _write_insert(table: str, values: dict[str, Any], conflict_field: str | None = None) -> Any:
    try:
        with contract_engine().begin() as conn:
            _create_missing(conn)
            _assume_motion_api(conn)
            present = _column_types(conn, table)
            payload = {key: value for key, value in values.items() if key in present}
            missing = [key for key in values if key not in present and key != "locked_at"]
            if missing:
                raise ContractError(500, f"{table} is missing columns: {', '.join(missing)}")
            id_column = _row_id_column(table, present)
            sql = (
                f"INSERT INTO {table} ({', '.join(payload)}) "
                f"VALUES ({', '.join(_placeholder(name, present[name]) for name in payload)}) "
                f"RETURNING {id_column}"
            )
            try:
                row = conn.execute(text(sql), _binds(payload, present)).one()
            except IntegrityError as exc:
                if conflict_field and _is_unique(exc):
                    raise ContractError(409, f"{conflict_field} already exists") from exc
                raise ContractError(400, _safe_db_message(exc)) from exc
            except (ProgrammingError, DBAPIError) as exc:
                if _is_rls(exc):
                    raise ContractError(403, "rejected by row level security") from exc
                raise ContractError(500, _safe_db_message(exc)) from exc
            return row[0]
    except (ProgrammingError, DBAPIError) as exc:
        if _is_rls(exc):
            raise ContractError(403, "rejected by row level security") from exc
        raise


def _write_upsert(table: str, values: dict[str, Any], pk: str) -> Any:
    if table == "sim_runs":
        raise ContractError(500, "sim_runs is insert-only")
    try:
        with contract_engine().begin() as conn:
            _create_missing(conn)
            _assume_motion_api(conn)
            present = _column_types(conn, table)
            payload = {key: value for key, value in values.items() if key in present}
            missing = [key for key in values if key not in present]
            if missing:
                raise ContractError(500, f"{table} is missing columns: {', '.join(missing)}")
            if pk not in present:
                raise ContractError(500, f"{table} is missing primary key {pk}")
            id_column = _row_id_column(table, present)
            assignments = ", ".join(
                f"{name} = excluded.{name}" for name in payload if name != pk
            )
            sql = (
                f"INSERT INTO {table} ({', '.join(payload)}) "
                f"VALUES ({', '.join(_placeholder(name, present[name]) for name in payload)}) "
                f"ON CONFLICT ({pk}) DO UPDATE SET {assignments} "
                f"RETURNING {id_column}"
            )
            try:
                row = conn.execute(text(sql), _binds(payload, present)).one()
            except (ProgrammingError, DBAPIError) as exc:
                if _is_rls(exc):
                    raise ContractError(403, "rejected by row level security") from exc
                raise ContractError(500, _safe_db_message(exc)) from exc
            return row[0]
    except (ProgrammingError, DBAPIError) as exc:
        if _is_rls(exc):
            raise ContractError(403, "rejected by row level security") from exc
        raise


def _assume_motion_api(conn: Connection) -> None:
    """Apply RLS as motion_api. Local SQLite has no roles."""
    if conn.dialect.name != "postgresql":
        return
    current = conn.execute(text("SELECT current_user")).scalar()
    if current == "motion_api":
        return
    try:
        conn.execute(text("SET LOCAL ROLE motion_api"))
    except (ProgrammingError, DBAPIError) as exc:
        raise ContractError(503, "motion_api role is required for writes") from exc
    _separate_from_muse(conn)


def _create_missing(conn: Connection) -> None:
    if conn.dialect.name == "sqlite":
        for statement in _SQLITE_DDL:
            conn.execute(text(statement))
        return
    _separate_from_muse(conn)
    created: list[str] = []
    for statement in _POSTGRES_TABLES:
        name = _table_name_from_ddl(statement)
        if _table_exists(conn, name):
            continue
        conn.execute(text(statement))
        created.append(name)
    if "sim_runs" in created:
        conn.execute(text(_POSTGRES_LOCK))
        conn.execute(text(_POSTGRES_TRIGGER))
        conn.execute(text(_POSTGRES_TRIGGER_CREATE))
    if created and _role_exists(conn, "motion_api"):
        for name in created:
            _grant_motion_api(conn, name)


def _grant_motion_api(conn: Connection, table: str) -> None:
    conn.execute(text(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY"))
    conn.execute(text(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY"))
    if table in {"events", "zones"}:
        privileges = "INSERT, SELECT, UPDATE"
        conn.execute(
            text(
                f"CREATE POLICY motion_api_insert ON {table} "
                f"FOR INSERT TO motion_api WITH CHECK (true)"
            )
        )
        conn.execute(
            text(
                f"CREATE POLICY motion_api_select ON {table} "
                f"FOR SELECT TO motion_api USING (true)"
            )
        )
        conn.execute(
            text(
                f"CREATE POLICY motion_api_update ON {table} "
                f"FOR UPDATE TO motion_api USING (true) WITH CHECK (true)"
            )
        )
    else:
        privileges = "INSERT, SELECT"
        conn.execute(
            text(
                f"CREATE POLICY motion_api_insert ON {table} "
                f"FOR INSERT TO motion_api WITH CHECK (true)"
            )
        )
        conn.execute(
            text(
                f"CREATE POLICY motion_api_select ON {table} "
                f"FOR SELECT TO motion_api USING (true)"
            )
        )
    conn.execute(text(f"GRANT {privileges} ON {table} TO motion_api"))
    if table == "sim_runs":
        conn.execute(text("REVOKE UPDATE, DELETE ON sim_runs FROM motion_api"))
        conn.execute(text("GRANT USAGE, SELECT ON SEQUENCE sim_runs_id_seq TO motion_api"))
    elif table in {"occupancy_samples", "drink_events"}:
        conn.execute(text(f"REVOKE UPDATE, DELETE ON {table} FROM motion_api"))
        conn.execute(text(f"GRANT USAGE, SELECT ON SEQUENCE {table}_id_seq TO motion_api"))


def _table_name_from_ddl(statement: str) -> str:
    for name in TABLES:
        if f"TABLE IF NOT EXISTS {name}" in statement:
            return name
    raise RuntimeError("contract DDL is missing a known table name")


def _separate_from_muse(conn: Connection) -> None:
    """Keep locked sims off the muse `public.sim_runs` table.

    The panel list reads muse columns (`kind`, `created_at`). The locked
    contract uses `sim_id`. On Postgres those cannot share one table.
    If `public.sim_runs` is already the contract shape, writes stay there.
    """
    public_cols = _columns_in_schema(conn, "public", "sim_runs")
    if "sim_id" in public_cols:
        return
    current = conn.execute(text("SELECT current_user")).scalar()
    if current != "motion_api":
        conn.execute(text("CREATE SCHEMA IF NOT EXISTS motion_contract"))
        if _role_exists(conn, "motion_api"):
            conn.execute(text("GRANT USAGE ON SCHEMA motion_contract TO motion_api"))
    conn.execute(text("SET LOCAL search_path TO motion_contract"))


def _columns_in_schema(conn: Connection, schema: str, table: str) -> set[str]:
    rows = conn.execute(
        text(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema = :schema AND table_name = :name"
        ),
        {"schema": schema, "name": table},
    ).all()
    return {str(row[0]) for row in rows}


def _role_exists(conn: Connection, role: str) -> bool:
    if conn.dialect.name != "postgresql":
        return False
    row = conn.execute(text("SELECT 1 FROM pg_roles WHERE rolname = :name"), {"name": role}).first()
    return row is not None


def _table_exists(conn: Connection, name: str) -> bool:
    if conn.dialect.name == "sqlite":
        row = conn.execute(
            text("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = :name"),
            {"name": name},
        ).first()
        return row is not None
    row = conn.execute(
        text(
            "SELECT 1 FROM information_schema.tables "
            "WHERE table_schema = current_schema() AND table_name = :name"
        ),
        {"name": name},
    ).first()
    return row is not None


def _column_types(conn: Connection, table: str) -> dict[str, str]:
    if conn.dialect.name == "sqlite":
        rows = conn.execute(text(f"PRAGMA table_info({table})")).all()
        return {str(row[1]): str(row[2] or "") for row in rows}
    rows = conn.execute(
        text(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_schema = current_schema() AND table_name = :name"
        ),
        {"name": table},
    ).all()
    return {str(row[0]): str(row[1]) for row in rows}


def _row_id_column(table: str, columns: dict[str, str]) -> str:
    if table == "events" and "event_id" in columns:
        return "event_id"
    if table == "zones" and "zone_id" in columns:
        return "zone_id"
    if "id" in columns:
        return "id"
    if table == "sim_runs" and "sim_id" in columns:
        return "sim_id"
    raise ContractError(500, f"{table} has no id column")


def _placeholder(name: str, data_type: str) -> str:
    kind = data_type.lower()
    if kind in {"json", "jsonb"}:
        return f"CAST(:{name} AS {kind})"
    if "timestamp" in kind:
        return f"CAST(:{name} AS timestamptz)"
    return f":{name}"


def _binds(payload: dict[str, Any], types: dict[str, str]) -> dict[str, Any]:
    bound: dict[str, Any] = {}
    for name, value in payload.items():
        kind = types.get(name, "").lower()
        if isinstance(value, (dict, list)):
            bound[name] = json.dumps(value, separators=(",", ":"))
        elif isinstance(value, datetime):
            bound[name] = value.isoformat()
        else:
            bound[name] = value
    return bound


def _require_object(body: dict[str, Any], required: set[str]) -> dict[str, Any]:
    if not isinstance(body, dict):
        raise ContractError(400, "body must be an object")
    missing = sorted(key for key in required if key not in body or body[key] is None)
    if missing:
        raise ContractError(400, f"missing field: {missing[0]}")
    return body


def _allow(body: dict[str, Any], allowed: set[str]) -> None:
    unknown = sorted(set(body) - allowed)
    if unknown:
        raise ContractError(400, f"unknown field: {unknown[0]}")


def _reject_tree(value: Any, banned: set[str]) -> None:
    if isinstance(value, dict):
        for key, item in value.items():
            if str(key).lower() in banned:
                raise ContractError(400, f"forbidden field: {key}")
            _reject_tree(item, banned)
    elif isinstance(value, list):
        for item in value:
            _reject_tree(item, banned)


def _ident(value: Any, field: str) -> str:
    text_value = _text(value, field, 128)
    if any(char in text_value for char in "\x00\n\r"):
        raise ContractError(400, f"{field} has invalid characters")
    return text_value


def _text(value: Any, field: str, limit: int) -> str:
    if not isinstance(value, str):
        raise ContractError(400, f"{field} must be a string")
    cleaned = value.strip()
    if not cleaned:
        raise ContractError(400, f"{field} is required")
    if len(cleaned) > limit:
        raise ContractError(400, f"{field} is too long")
    return cleaned


def _optional_text(value: Any, field: str, limit: int) -> str | None:
    if value is None:
        return None
    return _text(value, field, limit)


def _int(value: Any, field: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int):
        raise ContractError(400, f"{field} must be an integer")
    return value


def _optional_int(value: Any, field: str) -> int | None:
    if value is None:
        return None
    number = _int(value, field)
    if number < 0:
        raise ContractError(400, f"{field} must be zero or greater")
    return number


def _number(value: Any, field: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ContractError(400, f"{field} must be a number")
    if isinstance(value, float) and value != value:
        raise ContractError(400, f"{field} must be a number")
    return float(value)


def _optional_number(value: Any, field: str) -> float | None:
    if value is None:
        return None
    number = _number(value, field)
    if number < 0:
        raise ContractError(400, f"{field} must be zero or greater")
    return number


def _json_object(value: Any, field: str) -> dict[str, Any]:
    parsed = _parse_json(value, field)
    if not isinstance(parsed, dict):
        raise ContractError(400, f"{field} must be an object")
    if len(json.dumps(parsed)) > 262144:
        raise ContractError(400, f"{field} is too long")
    return parsed


def _json_curve(value: Any) -> Any:
    parsed = _parse_json(value, "predicted_peak_curve")
    if not isinstance(parsed, (dict, list)):
        raise ContractError(400, "predicted_peak_curve must be an object or array")
    if isinstance(parsed, list) and len(parsed) > 5000:
        raise ContractError(400, "predicted_peak_curve is too long")
    if len(json.dumps(parsed)) > 262144:
        raise ContractError(400, "predicted_peak_curve is too long")
    return parsed


def _parse_json(value: Any, field: str) -> Any:
    if isinstance(value, str):
        try:
            return json.loads(value)
        except json.JSONDecodeError as exc:
            raise ContractError(400, f"{field} must be JSON") from exc
    return value


def _timestamp(value: Any, field: str) -> datetime:
    if isinstance(value, bool):
        raise ContractError(400, f"{field} must be a timestamp")
    if isinstance(value, (int, float)):
        if isinstance(value, float) and value != value:
            raise ContractError(400, f"{field} must be a timestamp")
        try:
            return datetime.fromtimestamp(float(value), tz=timezone.utc)
        except (OverflowError, OSError, ValueError) as exc:
            raise ContractError(400, f"{field} must be a timestamp") from exc
    if isinstance(value, str):
        raw = value.strip()
        if raw.endswith("Z"):
            raw = raw[:-1] + "+00:00"
        try:
            parsed = datetime.fromisoformat(raw)
        except ValueError as exc:
            raise ContractError(400, f"{field} must be a timestamp") from exc
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=timezone.utc)
        return parsed.astimezone(timezone.utc)
    raise ContractError(400, f"{field} must be a timestamp")


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _is_unique(exc: IntegrityError) -> bool:
    orig = getattr(exc, "orig", None)
    code = getattr(orig, "sqlstate", None) or getattr(orig, "pgcode", None)
    if code == "23505":
        return True
    return "unique" in str(orig or exc).lower()


def _is_rls(exc: Exception) -> bool:
    orig = getattr(exc, "orig", exc)
    code = getattr(orig, "sqlstate", None) or getattr(orig, "pgcode", None)
    message = str(orig).lower()
    return code == "42501" or "row-level security" in message or "permission denied" in message


def _safe_db_message(exc: Exception) -> str:
    message = str(getattr(exc, "orig", exc))
    if "://" in message or "password" in message.lower():
        return "database write failed"
    return message[:300]
