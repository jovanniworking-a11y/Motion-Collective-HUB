"""Agent write contract for the Neon data platform.

Counts, zones, passes, and locked sim predictions only. No guest names,
no venue address, no frames.

`sim_runs` is insert-only. This module never issues UPDATE or DELETE
against that table. When this process creates the table, a trigger
rejects both, and `motion_api` is not granted those privileges.

Postgres sessions write as `motion_api` (`SET LOCAL ROLE`) so existing
row-level security policies apply. SQLite tests use a sibling file,
`motion_contract.sqlite3`, because the local muse tables reuse three
of these names with a different column set.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import create_engine, text
from sqlalchemy.engine import Connection, Engine
from sqlalchemy.exc import DBAPIError, IntegrityError, ProgrammingError

from .platform_db import DATA_DIR, DATABASE_URL, get_engine

BANNED_KEYS = {
    "address",
    "venue_address",
    "guest",
    "guests_named",
    "guest_name",
    "phone",
    "email",
    "face",
    "faces",
    "embedding",
    "image",
    "image_path",
    "boxes",
    "track_id",
    "track_ids",
}

# Event and zone rows use `name` for the event or zone, not a person.
PERSON_KEYS = BANNED_KEYS | {"name", "names"}

TABLES = ("events", "zones", "sim_runs", "occupancy_samples", "drink_events")

